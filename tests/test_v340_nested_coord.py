class NestedCoordinationTest(unittest.TestCase):
    def test_reordered_clauses_are_quiet(self):
        """並べた節の順を入れ替えただけの推敲には swap も nested も出さない。"""
        for form, before, after in NOT_FOUND:
            with self.subTest(form=form, before=before, after=after):
                result = run(before, after)
                self.assertEqual(swaps(result), [])
                self.assertEqual(result["fail_on_meaning_risk_count"], 0)

    def test_lookalike_words_stay_coordinated(self):
        """決まった言い方の語と同じ字で始まる語が2つ目の節の頭に来ても、並べた節として見ない。"""
        for form, before, after in LOOKALIKE:
            with self.subTest(form=form, before=before, after=after):
                self.assertEqual(swaps(run(before, after)), [])
                self.assertIsNone(yomiyasu_diff._nest_roles(before))
                self.assertIsNone(yomiyasu_diff._nest_roles(after))
                self.assertEqual(joints(before)[:1], ["と"])

    def test_fixed_phrases_are_still_examined(self):
        """と のあとが一覧の決まった言い方の文と、と が「ところ」「とき」の頭の字の文は、3.3.0 と同じく nested を出す。"""
        for form, before, after, pairs in FOUND:
            with self.subTest(form=form, before=before, after=after):
                found = swaps(run(before, after))
                self.assertEqual([(risk["kind"], risk["subkind"]) for risk in found], [("swap", "nested")])
                self.assertEqual(found[0]["detail"], {"pairs": pairs})

    def test_other_joints_are_still_examined(self):
        """直しの外のつなぎ（〜し、、〜て、たり、とともに、ほか、だけでなく、のみならず、や否や、か、あるいは、若しくは、ないし）で
        並べた節は今までどおり見る。"""
        for form, before, after, pairs in OTHER_JOINT_FOUND:
            with self.subTest(form=form, before=before, after=after):
                found = swaps(run(before, after))
                self.assertEqual([(risk["kind"], risk["subkind"]) for risk in found], [("swap", "nested")])
                self.assertEqual(found[0]["detail"], {"pairs": pairs})
        for form, sentence in OTHER_JOINT_EXAMINED:
            with self.subTest(form=form, sentence=sentence):
                self.assertIsNotNone(yomiyasu_diff._nest_roles(sentence))

    def test_other_joints_reordered_are_unchanged(self):
        """若しくは と ないし は並べた節のつなぎに数えないので、2つの節の順を入れ替えただけの推敲にも 3.3.0 と同じく nested が出る。"""
        for form, before, after in OTHER_JOINT_REORDERED:
            with self.subTest(form=form, before=before, after=after):
                self.assertEqual(joints(before), [])
                self.assertEqual([(risk["kind"], risk["subkind"]) for risk in swaps(run(before, after))], [("swap", "nested")])

    def test_known_misses(self):
        """並べた節の文の本当の入れ替えと、一覧の外の決まった言い方と、並べた節でない の＋と の文は出ない（文書の限界）。"""
        for reason, before, after in MISSED:
            with self.subTest(reason=reason, before=before, after=after):
                self.assertEqual(swaps(run(before, after)), [])
                self.assertIsNone(yomiyasu_diff._nest_roles(before))

    def test_nest_roles_is_none_for_coordinated_clauses(self):
        """並べた節のつなぎがある文は、名詞化の語の数によらず _nest_roles が None。つなぎは _NEST_NOMINAL の1つ目のかっこに入る。"""
        self.assertEqual(yomiyasu_diff._NEST_NOMINAL.groups, 1)
        for joint, sentence in COORDINATED:
            with self.subTest(joint=joint, sentence=sentence):
                self.assertIsNone(yomiyasu_diff._nest_roles(sentence))
                self.assertEqual(joints(sentence)[:1], [joint])

    def test_nest_roles_for_fixed_phrases(self):
        """決まった言い方の と は並べた節のつなぎにしないので、役は 3.3.0 と同じ。"""
        for sentence, roles in FIXED_ROLES:
            with self.subTest(sentence=sentence):
                self.assertEqual(yomiyasu_diff._nest_roles(sentence), roles)
                self.assertEqual(joints(sentence), [])

    def test_fixed_fragments(self):
        """docs/limitations.md の一覧の形の と と読点は、つなぎに数えない。"""
        for sentence in FIXED_FRAGMENTS:
            with self.subTest(sentence=sentence):
                self.assertEqual(joints(sentence), [])

    def test_joint_fragments(self):
        """一覧の語と同じ字で始まる語の前の と、一覧の外の形の と、と のすぐあとに読点を置いた形は、つなぎに数える。"""
        for sentence in JOINT_FRAGMENTS:
            with self.subTest(sentence=sentence):
                self.assertEqual(joints(sentence)[:1], ["と"])

    def test_na_no_with_case_particle_is_not_nominal(self):
        """な のあとの の に を、に、が、は、も が続く形は、3.3.0 と同じく名詞化の語にしない（並べた節の の だけ な のあとも取る）。"""
        for sentence in ("部屋は静かなのが一番だ。", "店員は丁寧なのを選んだ。", "画面が鮮明なのは助かる。"):
            with self.subTest(sentence=sentence):
                self.assertEqual(list(yomiyasu_diff._NEST_NOMINAL.finditer(sentence)), [])
                self.assertIsNone(yomiyasu_diff._nest_roles(sentence))

    def test_hidden_dropped_sentence_appears(self):
        """3.3.0 では消えた nested の陰に隠れていた、同じ元の行の消えた文の候補（dropped_sentence）が出る。数えない候補なので
        --fail-on は0のまま。"""
        for form, before, after in DROPPED:
            with self.subTest(form=form):
                result = run(before, after)
                self.assertEqual([(risk["kind"], risk["old_line"]) for risk in result["meaning_risks"]],
                                 [("dropped_sentence", 1)])
                self.assertEqual(result["fail_on_meaning_risk_count"], 0)


