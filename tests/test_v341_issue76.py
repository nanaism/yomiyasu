def run(old, new):
    return yomiyasu_diff.diff(old + "\n", new + "\n")


def numbers(old, new):
    """数値の候補の (subkind, 消えた値, 足した値) の並びと、--fail-on=meaning-risk に数える数。"""
    result = run(old, new)
    found = [(risk["subkind"], risk["detail"]["removed"], risk["detail"]["added"])
             for risk in result["meaning_risks"] if risk["kind"] == "number"]
    return found, result["fail_on_meaning_risk_count"]


def kinds(old, new):
    result = run(old, new)
    return [(risk["kind"], risk["subkind"]) for risk in result["meaning_risks"]], result["fail_on_meaning_risk_count"]


def slide_hits(text):
    result = yomiyasu_lint.lint_text(text, doc_type="slides")
    return [(f["line"], f["message"].split("当たった言い方: ")[1].split("）")[0]) for f in result["findings"] if f["rule"] == "slide_comma"]


