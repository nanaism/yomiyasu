class WordingTest(unittest.TestCase):
    def wording(self, text):
        return [yomiyasu_diff._addition_promise_wording(text, pos, key, name)
                for sub, name, key, pos, _ in yomiyasu_diff._addition_promise_clauses(text) if sub in ("guarantee", "prevention")]

    def test_limiter_kind(self):
        """範囲や条件を決める語は外し、その種類を句の前の語のあとに付ける。重ねて付いた助詞も外す。"""
        self.assertEqual(self.wording("品質だけは担保されます。"), [("品質のみ", "担保されます")])
        self.assertEqual(self.wording("旧プランでのみ引き続きご利用いただけます。"), [("旧プランのみ", "引き続きご利用いただけます")])
        self.assertEqual(self.wording("旧プランでさえも引き続きご利用いただけます。"), [("旧プランさえ", "引き続きご利用いただけます")])
        self.assertEqual(self.wording("法人会員を除き、引き続きご利用いただけます。"), [("法人会員以外", "引き続きご利用いただけます")])
        self.assertEqual(self.wording("法人会員以外は引き続きご利用いただけます。"), [("法人会員以外", "引き続きご利用いただけます")])
        self.assertEqual(self.wording("旧プランであれば引き続きご利用いただけます。"), [("旧プランなら", "引き続きご利用いただけます")])
        self.assertEqual(self.wording("特別な事情がない限り、追加の費用は発生いたしません。"), [("なら", "追加の費用は発生いたしません")])
        self.assertEqual(self.wording("設定を変えなければ、追加の費用は発生いたしません。"), [("なら", "追加の費用は発生いたしません")])
        self.assertEqual(self.wording("解約したら、追加の費用は発生いたしません。"), [("なら", "追加の費用は発生いたしません")])
        self.assertEqual(self.wording("例えば、追加の費用は発生いたしません。"), [("", "追加の費用は発生いたしません")])

    def test_no_word(self):
        """語が取れないときは、3.2.1 と同じく語を空にする（範囲や条件を決める語の種類だけは残す）。"""
        self.assertEqual(self.wording("旧プランを含めて引き続きご利用いただけます。"), [("", "引き続きご利用いただけます")])
        self.assertEqual(self.wording("なお、追加の費用は発生いたしません。"), [("", "追加の費用は発生いたしません")])
        self.assertEqual(self.wording("ご利用中のものだけ、引き続きご利用いただけます。"), [("のみ", "引き続きご利用いただけます")])

    def test_kana_map(self):
        """漢字の形をそろえた文と、元の文の位置からの対応。"""
        kana, mapping = yomiyasu_diff._addition_kana_map("ご負担頂く事は一致します")
        self.assertEqual(kana, "ご負担いただくことは一いたします")
        self.assertEqual(len(mapping), len("ご負担頂く事は一致します") + 1)
        self.assertEqual(mapping[-1], len(kana))
        self.assertEqual(kana[mapping[4]], "く")
        for text, want in [("発生致しません", "発生いたしません"), ("発送致しました", "発送いたしました"),
                           ("ご入力頂いた", "ご入力いただいた"), ("お手続き頂かなくても", "お手続きいただかなくても"),
                           ("本人確認が出来れば", "本人確認ができれば"), ("移行の為、", "移行のため、"),
                           ("ご確認下さい", "ご確認ください"), ("試して見る", "試してみる"),
                           ("為替の出来事は大事にする", "為替の出来事は大事にする")]:
            with self.subTest(text=text):
                self.assertEqual(yomiyasu_diff._addition_kana_map(text)[0], want)


