class ContrastAlsoAndCoordinationTest(unittest.TestCase):
    """反証で見つけた例: 重みの語がない「AだけでなくB」「AとB」の逆転を拾う。比べた形と原文の「Aだけでなく」は出さない。"""

    def test_also_forms_are_found(self):
        for before, after, word in ALSO_FOUND:
            with self.subTest(after=after):
                self.assertIn(word, reversal_words(before, after))

    def test_coordination_is_found(self):
        for before, after, word in COORD_FOUND:
            with self.subTest(after=after):
                self.assertIn(word, reversal_words(before, after))

    def test_found_with_doc_type(self):
        """種類の指定によらない（反証で見つけた例を --doc-type incident で）。"""
        before, after, word = COORD_FOUND[0]
        self.assertIn(word, reversal_words(before, after, "incident"))

    def test_compared_or_quoted_pairs_are_not_found(self):
        for before, after in COORD_NOT_FOUND:
            with self.subTest(after=after):
                self.assertEqual(reversal_words(before, after), [])

    def test_not_only_in_the_original_is_not_contrast(self):
        for before, after in NOT_ONLY_IN_ORIGINAL:
            with self.subTest(before=before):
                self.assertEqual(reversal_words(before, after), [])

    def test_still_not_counted_for_fail_on(self):
        result = result_of(*COORD_FOUND[0][:2])
        self.assertIn("contrast_reversal", [risk["kind"] for risk in result["meaning_risks"]])
        self.assertEqual(result["fail_on_meaning_risk_count"], 0)


