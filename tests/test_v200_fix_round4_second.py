class KnownLimitsSecondTest(unittest.TestCase):
    def test_order_swaps_with_the_same_clues(self):
        """数値の直前の2字とあとの語が同じ入れ替えは、並びの候補にしない（前の版から同じ）。"""
        cases = (
            ("上限は10GB、下限は500MBです。", "上限は500MB、下限は10GBです。"),
            ("東館は5階、西館は8部屋ある。", "東館は8部屋、西館は5階ある。"),
            ("Aの会議は30分、Bの会議は2時間です。", "Aの会議は2時間、Bの会議は30分です。"),
            ("Aチームは5人で2週間、Bチームは3人で10日かけた。", "Aチームは3人で2週間、Bチームは5人で10日かけた。"),
        )
        for before, after in cases:
            with self.subTest(before=before):
                self.assertEqual(number_risks(before, after), [])

    def test_same_unit_reorder_is_still_an_order_change(self):
        """同じ単位の数の前後を入れ替えただけの推敲は、並びの候補に出る（前からの限界）。"""
        self.assertEqual(number_risks("作業は1日8時間、週に40時間までにする。", "作業は週に40時間、1日8時間までにする。"),
                         [("order", ["1日", "8時間", "40時間"], ["40時間", "1日", "8時間"])])

    def test_replace_forms_not_covered(self):
        h = "## 手作業ではなく自動化で回す"
        z = "外部の認証は使わず、自前の認証を作る。"
        # 正しい推敲でも逆転の候補に出る形（読点を挟む、変える）
        self.assertEqual(reversal_words(z, "第一に、外部の認証を、自前の認証に置き換える。"), ["外部"])
        self.assertEqual(reversal_words(h, "## まず、手作業をスクリプトに変える"), ["手作業"])
        # 原文で肯定した側の語（自動化）に変える形は、あとの直しで逆転にしなくなった（test_v200_fix_round5.py）
        self.assertEqual(reversal_words(h, "## まず、手作業を自動化に変える"), [])
        # A を採ったのに逆転の候補にしない形（置き換え先が一覧にない、A を使う句の語が一覧にない）
        self.assertEqual(reversal_words("試作版ではなく、今の版を使い続ける。", "まず、試作版を正式版に移行する。"), [])
        self.assertEqual(reversal_words("クラウドではなく、オンプレミスで運用する。", "まず、クラウドを土台にした構成に移行する。"), [])

    def test_demote_words_not_covered(self):
        """下げる語は平仮名の「そのあとに回す」だけ。「その後に回す」「次に見る」「其の次に見る」は正しい推敲でも候補に出る。"""
        before = "キャッシュではなく、DNSの設定を疑う。"
        for after in ("まずDNSの設定を疑い、キャッシュはその後に回す。", "まずDNSの設定を疑い、キャッシュは次に見る。",
                      "まずDNSの設定を疑い、キャッシュは其の次に見る。"):
            with self.subTest(after=after):
                self.assertEqual(reversal_words(before, after), ["キャッシュ"])
        for after in ("まずDNSの設定を疑い、キャッシュはそのあとに回す。", "まずDNSの設定を疑い、キャッシュはその次に見る。"):
            with self.subTest(after=after):
                self.assertEqual(reversal_words(before, after), [])

    def test_one_each_without_a_verb(self):
        """「一つずつどうぞ」（ずつ のあとに動詞がない）は、相手の文のどこかの「複数」「いくつか」で変わったとみなす。"""
        cases = (
            ("質問は一つずつどうぞ。", "質問は順番にどうぞ。複数ある方も順番にお願いします。"),
            ("ご意見は一つずつどうぞ。", "ご意見は、いくつかある場合も順番にどうぞ。"),
        )
        for before, after in cases:
            with self.subTest(before=before):
                self.assertEqual(number_risks(before, after), [("lost", ["一つ"], [])])


