"""3.4.0（▲△の符号）: ▲と△を負の符号に読む（符号の候補 number_sign。符号の消えも拾う形）。負の向きの言い方に言い換えた推敲と、
符号に読まない形（▼のある行の続きと表、評価の印、行頭の箇条の印、年・月・/ の前、将棋の指し手）は出さない。

3.3.0 が出していた ▲△ と「-」の書き方だけの違いの誤った候補（△120万円 → -120万円）も出さない。文はすべて合成の文。
"""
from pathlib import Path
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import yomiyasu_diff  # noqa: E402

SIGNS = "+−-▲△ "


def number_risks(old, new):
    return [risk for risk in yomiyasu_diff.diff(old + "\n", new + "\n")["meaning_risks"] if risk["kind"] == "number"]


def sign_risks(old, new):
    out = []
    for risk in yomiyasu_diff.diff(old + "\n", new + "\n")["meaning_risks"]:
        detail = risk.get("detail") or {}
        removed, added = detail.get("removed") or [], detail.get("added") or []
        if (risk["kind"] == "number" and removed and added
                and sorted(v.lstrip(SIGNS) for v in removed) == sorted(v.lstrip(SIGNS) for v in added)
                and sorted(removed) != sorted(added)):
            out.append((removed, added))
    return out


