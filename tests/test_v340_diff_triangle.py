                ("売上高は前年比▲3%、客数は前年比3%増でした。", "売上高は前年より3%減り、客数は3%増えました。"),
                ("売上高は▲3%、営業利益は▲5%でした。", "売上高は3%、営業利益は5%、いずれも前年を下回りました。"),
