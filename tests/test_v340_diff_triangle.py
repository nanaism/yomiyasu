                ("減収の中でも、営業利益は▲1%にとどめた。", "減収の中でも、営業利益の落ち込みは1%にとどめた。"),
                ("小計 12,000円\n値引き ▲1,000円\n合計 11,000円", "小計 12,000円\n値引き 1,000円\n合計 11,000円"),
