class SameWordsTest(unittest.TestCase):
    def test_target_words_are_normalized(self):
        norm = yomiyasu_diff._addition_target_norm
        for words, want in ((("当社", "弊社", "小社", "自社"), "当社"), (("御社", "貴社"), "御社"), (("今", "現在", "現行"), "現在"),
                            (("担当者", "担当者様", "ご担当者様"), "担当者"), (("お客様", "お客さま", "客", "顧客", "ユーザー", "利用者"), "利用者"),
                            (("皆様", "皆さま", "みなさま", "方", "方々", "各位"), "人"), (("既存", "利用中", "契約", "契約中"), "既存"),
                            (("旧バージョン", "旧版"), "旧版"), (("有償プラン", "有料プラン"), "有料プラン")):
            for word in words:
                with self.subTest(word=word):
                    self.assertEqual(norm(word), want)

    def test_contrasting_words_stay_different(self):
        norm = yomiyasu_diff._addition_target_norm
        for a, b in (("旧プラン", "新プラン"), ("法人", "個人"), ("保護者", "生徒"), ("有料プラン", "無料プラン"), ("当社", "御社"),
                     ("既存", "新規")):
            with self.subTest(a=a, b=b):
                self.assertNotEqual(norm(a), norm(b))


